export const GLYPH_WIDTH = 5
export const GLYPH_HEIGHT = 7
/** One blank column between characters. */
export const GLYPH_ADVANCE = GLYPH_WIDTH + 1

export const SUPPORTED_CHARACTERS = Object.keys(GLYPHS).join('')

export function normalizeText(value: string) {
  return Array.from(value.toUpperCase())
    .filter((character) => character in GLYPHS)
    .join('')
}

export function textWidthInWeeks(text: string) {
  if (!text.length) return 0
  return text.length * GLYPH_ADVANCE - 1
}

/** Returns [column, row] pairs that the text lights up, relative to its own origin. */
export function textPixels(text: string): Array<[number, number]> {
  const pixels: Array<[number, number]> = []
  Array.from(text).forEach((character, characterIndex) => {
    const glyph = GLYPHS[character]
    if (!glyph) return
    glyph.split('|').forEach((rowPattern, row) => {
      Array.from(rowPattern).forEach((pixel, column) => {
        if (pixel === '#') pixels.push([characterIndex * GLYPH_ADVANCE + column, row])
      })
    })
  })
  return pixels
}
